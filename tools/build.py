def wrap_text(text: str, max_chars: int) -> list[str]:
    words, lines, cur = text.split(), [], ""
    for w in words:
        if not cur:
            cur = w
        elif len(cur) + 1 + len(w) <= max_chars:
            cur += " " + w
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


def layout_tags(tags: list[str], width: float, char_w: float, pad: float, gap: float) -> list[list[tuple[str, float]]]:
    rows, cur, cur_w = [], [], 0.0
    for t in tags:
        w = len(t) * char_w + pad * 2
        if cur and cur_w + gap + w > width:
            rows.append(cur)
            cur, cur_w = [], 0.0
        cur.append((t, w))
        cur_w += (gap if cur_w else 0) + w
    if cur:
        rows.append(cur)
    return rows


def pipeline_svg(pipe: dict, cols: int, uid: str) -> str:
    nodes = pipe["nodes"]
    n = len(nodes)
    cols = max(1, min(cols, n))
    W = 300 if cols == 1 else (250 if cols == 2 else 232)
    GX, GY = 44, 60
    PAD = 18
    LABEL_FS, DETAIL_FS, TAG_FS, NUM_FS = 17, 13, 11, 11
    LINE = DETAIL_FS * 1.42
    inner = W - PAD * 2
    detail_chars = int(inner / (DETAIL_FS * 0.53))
    tag_char_w = TAG_FS * 0.62

    prepared, heights = [], []
    for node in nodes:
        dl = wrap_text(node.get("detail", ""), detail_chars)
        tr = layout_tags(node.get("tags", []), inner, tag_char_w, 7, 6)
        h = PAD + NUM_FS + 10 + LABEL_FS + 10 + len(dl) * LINE + (8 + len(tr) * 26 if tr else 0) + PAD - 4
        prepared.append((node, dl, tr))
        heights.append(h)

    rows = math.ceil(n / cols)
    row_h = []
    for r in range(rows):
        row_h.append(max(heights[r * cols:(r + 1) * cols]))
    total_w = cols * W + (cols - 1) * GX
    total_h = sum(row_h) + (rows - 1) * GY
    ys = [sum(row_h[:r]) + r * GY for r in range(rows)]

    out = [f'<svg class="pipe__svg" viewBox="-2 -2 {total_w + 4} {total_h + 4}" width="{total_w + 4}" '
           f'aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg">',
           f'<defs><marker id="arw-{uid}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" '
           f'orient="auto-start-reverse"><path d="M0 0L10 5L0 10z" class="pipe__arrowhead"/></marker></defs>']

    # connectors first, so boxes sit on top
    for i in range(n - 1):
        r, c = divmod(i, cols)
        r2, c2 = divmod(i + 1, cols)
        x1 = c * (W + GX) + W
        y1 = ys[r] + row_h[r] / 2
        if r == r2:
            x2 = c2 * (W + GX)
            out.append(f'<path d="M{x1:.1f} {y1:.1f}H{x2 - 2:.1f}" class="pipe__link" marker-end="url(#arw-{uid})"/>')
        elif cols == 1:
            x = W / 2
            yb = ys[r] + row_h[r]
            out.append(f'<path d="M{x:.1f} {yb:.1f}V{ys[r2] - 2:.1f}" class="pipe__link" marker-end="url(#arw-{uid})"/>')
        else:
            xs = c * (W + GX) + W / 2
            yb = ys[r] + row_h[r]
            ym = yb + GY / 2
            xe = c2 * (W + GX) + W / 2
            out.append(f'<path d="M{xs:.1f} {yb:.1f}V{ym:.1f}H{xe:.1f}V{ys[r2] - 2:.1f}" class="pipe__link" '
                       f'marker-end="url(#arw-{uid})"/>')

    for i, (node, dl, tr) in enumerate(prepared):
        r, c = divmod(i, cols)
        x = c * (W + GX)
        y = ys[r]
        h = row_h[r]
        kind = "custom" if node.get("custom") else node.get("kind", "step")
        out.append(f'<g class="pipe__node pipe__node--{kind}">')
        out.append(f'<rect x="{x}" y="{y}" width="{W}" height="{h:.1f}" rx="10" class="pipe__box"/>')
        ty = y + PAD + NUM_FS - 2
        num = f"{i + 1:02d}"
        badge = "  ·  MY NODE" if node.get("custom") else ""
        out.append(f'<text x="{x + PAD}" y="{ty:.1f}" class="pipe__num">{num}{badge}</text>')
        ty += 10 + LABEL_FS
        out.append(f'<text x="{x + PAD}" y="{ty:.1f}" class="pipe__label">{esc(node["label"])}</text>')
        ty += 8
        for line in dl:
            ty += LINE
            out.append(f'<text x="{x + PAD}" y="{ty - 3:.1f}" class="pipe__detail">{esc(line)}</text>')
        if tr:
            ty += 10
            for row in tr:
                tx = x + PAD
                for t, tw in row:
                    out.append(f'<rect x="{tx:.1f}" y="{ty:.1f}" width="{tw:.1f}" height="20" rx="10" class="pipe__tagbox"/>')
                    out.append(f'<text x="{tx + 7:.1f}" y="{ty + 14:.1f}" class="pipe__tag">{esc(t)}</text>')
                    tx += tw + 6
                ty += 26
        out.append("</g>")
    out.append("</svg>")
    return "".join(out)


def render_pipeline(key: str, pipelines: dict) -> str:
    pipe = pipelines[key]
    items = []
    for node in pipe["nodes"]:
        tags = node.get("tags") or []
        t = f" Options: {', '.join(tags)}." if tags else ""
        mine = " (my node)" if node.get("custom") else ""
        items.append(f"<li><strong>{esc(node['label'])}</strong>{mine}: {esc(node.get('detail', ''))}{esc(t)}</li>")
    svgs = "".join(
        f'<div class="pipe__view pipe__view--{c}">{pipeline_svg(pipe, c, f"{key}-{c}")}</div>' for c in (1, 2, 4)
    )
    return (
        f'<figure class="pipe" aria-label="{esc(pipe.get("title", key))}">{svgs}'
        f'<ol class="visually-hidden">{"".join(items)}</ol>'
        f'<figcaption class="pipe__legend"><span class="pipe__key pipe__key--custom" aria-hidden="true"></span> My custom node'
        f'<span class="pipe__key pipe__key--io" aria-hidden="true"></span> Input / output</figcaption></figure>'
    )


