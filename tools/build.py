def placeholder(title: str, label: str, expected: str, pal=None, extra_class: str = "", alt: str = "") -> str:
    """A cinematic slate frame shown until the real file exists.
    Add ?slots to any page URL to see the expected file path on each frame."""
    style = f' style="{palette_style(pal)}"' if pal else ""
    aria = esc(alt or f"{title}: {label}")
    return (
        f'<div class="ph {extra_class}"{style} role="img" aria-label="{aria}" data-expected="{esc(expected)}">'
        f'<span class="ph__corner ph__corner--tl" aria-hidden="true"></span>'
        f'<span class="ph__corner ph__corner--br" aria-hidden="true"></span>'
        f'<span class="ph__slate" aria-hidden="true">'
        f'<span class="ph__title">{esc(title)}</span>'
        f'<span class="ph__label">{esc(label)}</span>'
        f"</span>"
        f'<span class="ph__path" aria-hidden="true">{esc(expected)}</span>'
        f"</div>"
    )


def img_tag(src: str, alt: str, root: str, cls: str = "", eager: bool = False) -> str:
    loading = 'fetchpriority="high"' if eager else 'loading="lazy"'
    c = f' class="{cls}"' if cls else ""
    return f'<img{c} src="{root}{esc(src)}" alt="{esc(alt)}" {loading} decoding="async">'


def parse_embed(url: str):
    """Return (iframe_src, thumbnail_url_or_None, provider) for YouTube/Vimeo, else None."""
    if not url:
        return None
    u = urlparse(url)
    host = (u.hostname or "").lower().removeprefix("www.").removeprefix("m.")
    vid = None
    if host in ("youtube.com", "youtube-nocookie.com"):
        if u.path == "/watch":
            vid = parse_qs(u.query).get("v", [None])[0]
        else:
            m = re.match(r"^/(?:embed|shorts|live)/([\w-]{6,})", u.path)
            vid = m.group(1) if m else None
    elif host == "youtu.be":
        vid = u.path.strip("/").split("/")[0] or None
    if vid:
        return (
            f"https://www.youtube-nocookie.com/embed/{vid}?autoplay=1&rel=0&modestbranding=1",
            f"https://i.ytimg.com/vi/{vid}/hqdefault.jpg",
            "YouTube",
        )
    if host in ("vimeo.com", "player.vimeo.com"):
        m = re.search(r"/(\d{5,})", u.path)
        if m:
            return (f"https://player.vimeo.com/video/{m.group(1)}?autoplay=1&dnt=1", None, "Vimeo")
    return None


def lite_embed(url: str, poster: str, alt: str, title: str, label: str, pal, root: str) -> str:
    parsed = parse_embed(url)
    if not parsed:
        raise ValueError(f"unsupported embed URL: {url}")
    src, thumb, provider = parsed
    if exists(poster):
        visual = img_tag(poster, "", root)
    elif thumb:
        visual = f'<img src="{esc(thumb)}" alt="" loading="lazy" decoding="async" referrerpolicy="no-referrer">'
    else:
        visual = placeholder(title, label, poster or url, pal)
    return (
        f'<div class="embed" data-embed="{esc(src)}" data-title="{esc(alt or title)}">'
        f'<button class="embed__btn" type="button" aria-label="Play: {esc(alt or title)} (loads {provider})">'
        f"{visual}"
        f'<span class="embed__play" aria-hidden="true"><svg viewBox="0 0 24 24" width="28" height="28"><path d="M8 5v14l11-7z" fill="currentColor"/></svg></span>'
        f'<span class="embed__hint" aria-hidden="true">Play · {provider}</span>'
        f"</button></div>"
    )


def video_tag(src: str, poster: str, alt: str, root: str, mode: str) -> str:
    """mode: 'hero' (muted autoplay loop), 'loop' (muted loop, plays in view), 'controls' (full piece)."""
    p = f' poster="{root}{esc(poster)}"' if exists(poster) else ""
    if mode == "controls":
        return (f'<video class="media__video" controls playsinline preload="none"{p} aria-label="{esc(alt)}">'
                f'<source src="{root}{esc(src)}" type="video/mp4"></video>')
    autoplay = " autoplay" if mode == "hero" else ""
    preload = "auto" if mode == "hero" else "none"
    return (f'<video class="media__video" muted loop playsinline{autoplay} preload="{preload}"{p} '
            f'data-inview aria-label="{esc(alt)}"><source src="{root}{esc(src)}" type="video/mp4"></video>')


def render_visual(slot: dict, title: str, pal, root: str, mode: str = "loop", eager: bool = False) -> str:
    """Inner visual for a video/image/embed slot (no figure wrapper)."""
    t = slot.get("type")
    label = slot.get("label", t)
    alt = slot.get("alt", "")
    if t == "embed":
        if slot.get("url"):
            return lite_embed(slot["url"], slot.get("poster", ""), alt, title, label, pal, root)
        if exists(slot.get("src", "")):
            return video_tag(slot["src"], slot.get("poster", ""), alt, root, "controls")
        return placeholder(title, label, slot.get("src") or "(set url)", pal, "ph--film", alt)
    if t == "video":
        if slot.get("embed"):
            return lite_embed(slot["embed"], slot.get("poster", ""), alt, title, label, pal, root)
        if exists(slot.get("src", "")):
            return video_tag(slot["src"], slot.get("poster", ""), alt, root, mode)
        if exists(slot.get("poster", "")):
            return img_tag(slot["poster"], alt, root, eager=eager)
        return placeholder(title, label, slot.get("src", ""), pal, alt=alt)
    if t == "image":
        if exists(slot.get("src", "")):
            return img_tag(slot["src"], alt, root, eager=eager)
        return placeholder(title, label, slot.get("src", ""), pal, alt=alt)
    if t == "compare":
        return render_compare(slot, title, pal, root, bare=True)
    raise ValueError(f"unknown media type: {t}")


def aspect_style(slot: dict) -> str:
    a = slot.get("aspect")
    return f' style="--aspect:{esc(a)}"' if a else ""


def render_figure(slot: dict, title: str, pal, root: str, mode: str = "loop", cls: str = "", eager: bool = False) -> str:
    if slot.get("type") == "compare":
        return render_compare(slot, title, pal, root)
    cap = slot.get("caption")
    figcap = f"<figcaption>{inline(cap, root)}</figcaption>" if cap else ""
    return (f'<figure class="media {cls}"{aspect_style(slot)}><div class="media__frame">'
            f"{render_visual(slot, title, pal, root, mode, eager)}</div>{figcap}</figure>")


_compare_counter = 0


def render_compare(slot: dict, title: str, pal, root: str, bare: bool = False) -> str:
    global _compare_counter
    _compare_counter += 1
    cid = f"cmp-{_compare_counter}"
    label = slot.get("label", "Comparison")

    def side(key, which):
        src = slot.get(key, "")
        alt = slot.get(f"alt_{key}", f"{label}, {which}")
        if exists(src):
            return img_tag(src, alt, root)
        return placeholder(title, f"{label} · {which}", src, pal, f"ph--{key}", alt)

    cap = slot.get("caption")
    figcap = f'<figcaption id="{cid}-cap">{inline(cap, root)}</figcaption>' if cap else ""
    described = f' aria-describedby="{cid}-cap"' if cap else ""
    inner = (
        f'<div class="compare__frame" data-compare>'
        f'<div class="compare__layer compare__before">{side("before", "before")}</div>'
        f'<div class="compare__layer compare__after">{side("after", "after")}</div>'
        f'<span class="compare__tag compare__tag--before" aria-hidden="true">Before</span>'
        f'<span class="compare__tag compare__tag--after" aria-hidden="true">After</span>'
        f'<input class="compare__range" type="range" min="0" max="100" value="50" step="1" '
        f'aria-label="{esc(label)}: before and after. Arrow keys move the divider."{described} '
        f'aria-valuetext="50% after">'
        f'<span class="compare__handle" aria-hidden="true"><span class="compare__grip">'
        f'<svg viewBox="0 0 24 24" width="18" height="18"><path d="M9 6l-6 6 6 6M15 6l6 6-6 6" fill="none" stroke="currentColor" stroke-width="2"/></svg>'
        f"</span></span>"
        f"</div>"
    )
    if bare:
        return f'<div class="compare" style="--pos:50%">{inner}</div>'
    return f'<figure class="compare" style="--pos:50%"{aspect_style(slot)}>{inner}{figcap}</figure>'


