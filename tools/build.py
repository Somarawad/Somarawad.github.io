def og_image(site: dict, name: str) -> str:
    rel = f"assets/og/{name}.jpg"
    if not exists(rel):
        rel = "assets/og/default.jpg"
    return site["url"] + rel


def base_page(site: dict, *, root: str, title: str, description: str, canonical: str, og: str,
              content: str, body_class: str = "", og_type: str = "website", nav: str = "") -> str:
    tpl = load_template("base.html")
    page = render(tpl, {
        "title": esc(title),
        "og_title": esc(title),
        "description": esc(plain(description)),
        "canonical": esc(canonical),
        "og_type": og_type,
        "og_image": esc(og),
        "site_name": esc(site["name"]),
        "site_role": esc(site["role"]),
        "site_location": esc(site["location"]),
        "email": esc(site["email"]),
        "linkedin": esc(site["linkedin"]),
        "github": esc(site["github"]),
        "root": root,
        "version": ASSET_VERSION,
        "head_extra": "",
        "body_class": body_class,
        "nav_work": ' aria-current="page"' if nav == "work" else "",
        "nav_about": ' aria-current="page"' if nav == "about" else "",
        "content": content,
    })
    return page.replace("<!doctype html>", "<!doctype html>\n" + GENERATED_MARK, 1)


def build_home(site, projects) -> str:
    root = ""
    reel = site["showreel"]
    showreel = render_figure(reel, site["name"], site.get("palette"), root, mode="hero", cls="media--reel", eager=True)
    full = site.get("showreel_full") or {}
    reel_button = ""
    if full.get("url") or exists(full.get("src", "")):
        reel_button = '<a class="btn btn--ghost" href="#reel-full">Watch full reel</a>'
        showreel += (f'<div id="reel-full" class="reel-full">'
                     f'{render_figure(full, site["name"], site.get("palette"), root, mode="controls", cls="media--film")}</div>')
    flow = "".join(
        f'<li class="flow__step"><span class="flow__num" aria-hidden="true">{i + 1:02d}</span>{esc(s)}</li>'
        for i, s in enumerate(site.get("flow", []))
    )
    cards = "".join(render_card(p, root, i) for i, p in enumerate(projects))
    content = render(load_template("home.html"), {
        "site_role": esc(site["role"]),
        "site_location": esc(site["location"]),
        "headline": inline(site["headline"]),
        "supporting": inline(site["supporting"]),
        "email": esc(site["email"]),
        "reel_button": reel_button,
        "showreel": showreel,
        "flow": flow,
        "project_count": len(projects),
        "cards": cards,
        "tool_groups": render_tool_groups(site["about"]["tool_groups"]),
        "contact": render_contact(site),
    })
    return base_page(site, root=root, title=site["title"], description=site["description"],
                     canonical=site["url"], og=og_image(site, "default"), content=content,
                     body_class="page-home", nav="work")


def build_project(site, p, nxt, pipelines) -> str:
    root = "../../"
    pal = p.get("palette")
    hero = hero_slot(p)
    hero_html = render_figure(hero, p["title"], pal, root, mode="hero", cls="media--hero", eager=True) if hero else ""

    meta_items = [("Role", p.get("role")), ("Year", p.get("dates") or p.get("year"))]
    meta_items += [("Status", "Work in progress")] if p.get("wip") else []
    meta = "".join(f"<div><dt>{esc(k)}</dt><dd>{esc(v)}</dd></div>" for k, v in meta_items if v)

    note = ""
    if p.get("note"):
        cls = "note note--prominent" if p.get("note_prominent") else "note"
        note = f'<p class="{cls}"><span class="note__icon" aria-hidden="true">i</span>{inline(p["note"], root)}</p>'
    if p.get("wip"):
        note += ('<p class="note note--wip"><span class="note__icon" aria-hidden="true">◐</span>'
                 'Work in progress: the pipeline is built; the finished spot is still being made.</p>')

    did = "".join(f"<li>{inline(x, root)}</li>" for x in p.get("what_i_did", []))
    tools = ""
    if p.get("tools"):
        chips = "".join(f'<li class="chip">{esc(t)}</li>' for t in p["tools"])
        tools = f'<h3 class="label label--tools">Tools</h3><ul class="chips" role="list">{chips}</ul>'

    secs = list(p.get("sections", []))
    if not hero_html and secs and secs[0].get("type") == "stats":
        # Projects without hero media (the channel) lead with their stats card instead.
        lead = dict(secs.pop(0), heading="", intro="")
        hero_html = render_section(lead, p, pipelines, root).replace(" wrap\" data-reveal", "\"", 1)
    sections = "\n".join(render_section(s, p, pipelines, root) for s in secs)

    results = ""
    if p.get("results"):
        results = (f'<section class="block block--results wrap" data-reveal aria-labelledby="results-title">'
                   f'<h2 id="results-title" class="section__title">Results</h2>{stats_block(p["results"], "stats--big")}</section>')

    credits = ""
    if p.get("credits"):
        rows = "".join(f"<div><dt>{esc(c['role'])}</dt><dd>{esc(c['name'])}</dd></div>" for c in p["credits"])
        credits = f'<section class="credits" aria-labelledby="credits-title"><h2 id="credits-title" class="label">Credits</h2><dl class="meta meta--stack">{rows}</dl></section>'
    links = ""
    if p.get("links"):
        lis = []
        for l in p["links"]:
            url = l["url"]
            ext = url.startswith("http")
            href = url if ext else root + url
            rel = ' rel="noopener"' if ext else ""
            arrow = "↗" if ext else "→"
            lis.append(f'<li><a class="btn" href="{esc(href)}"{rel}>{esc(l["label"])} <span aria-hidden="true">{arrow}</span></a></li>')
        links = f'<section class="links" aria-labelledby="links-title"><h2 id="links-title" class="label">Links</h2><ul class="linklist" role="list">{"".join(lis)}</ul></section>'

    next_html = ""
    if nxt:
        next_html = (f'<nav class="next wrap" aria-label="Next project"><a class="next__link" href="{root}work/{nxt["slug"]}/">'
                     f'<span class="label">Next project</span>'
                     f'<span class="next__title">{esc(nxt.get("card_title") or nxt["title"])} <span class="arrow" aria-hidden="true">→</span></span>'
                     f'<span class="next__summary muted">{inline(nxt.get("tagline", ""))}</span></a></nav>')

    year = p.get("year")
    content = render(load_template("project.html"), {
        "root": root,
        "palette_style": palette_style(pal),
        "category": esc(p.get("category", "")),
        "year_eyebrow": f" · {esc(year)}" if year else "",
        "wip_badge": ' <span class="badge badge--wip badge--inline">Work in progress</span>' if p.get("wip") else "",
        "title": esc(p["title"]),
        "tagline": inline(p.get("tagline", ""), root),
        "meta": meta,
        "note": note,
        "hero": hero_html,
        "brief": inline(p.get("brief", ""), root),
        "what_i_did": did,
        "tools": tools,
        "sections": sections,
        "results": results,
        "credits": credits,
        "links": links,
        "next": next_html,
        "contact": render_contact(site),
    })
    desc = p.get("summary") or p.get("tagline", "")
    return base_page(site, root=root, title=f"{p['title']} · {site['name']}", description=desc,
                     canonical=f"{site['url']}work/{p['slug']}/", og=og_image(site, p["slug"]),
                     content=content, body_class="page-case", og_type="article", nav="work")


