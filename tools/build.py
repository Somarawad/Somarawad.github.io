def build_404(site) -> str:
    # 404.html is served by GitHub Pages at any missing URL, so it uses root-absolute paths.
    root = "/"
    content = render(load_template("404.html"), {"root": root, "email": esc(site["email"])})
    page = base_page(site, root=root, title=f"Page not found · {site['name']}", description=site["description"],
                     canonical=f"{site['url']}404.html", og=og_image(site, "default"), content=content,
                     body_class="page-404")
    return page.replace("<head>", '<head>\n<meta name="robots" content="noindex">', 1)


def build_sitemap(site, projects) -> str:
    urls = [site["url"], f"{site['url']}about/"] + [f"{site['url']}work/{p['slug']}/" for p in projects]
    body = "".join(f"  <url><loc>{esc(u)}</loc></url>\n" for u in urls)
    return f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{body}</urlset>\n'


def clean_stale_work_dirs(slugs: set) -> None:
    work = ROOT / "work"
    if not work.is_dir():
        return
    for d in work.iterdir():
        idx = d / "index.html"
        if d.is_dir() and d.name not in slugs and idx.is_file() and GENERATED_MARK in idx.read_text(encoding="utf-8"):
            shutil.rmtree(d)
            print(f"  removed work/{d.name}/ (project unpublished or renamed)")


def main() -> int:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    site = data["site"]
    pipelines = data.get("pipelines", {})
    projects = sorted((p for p in data["projects"] if p.get("published", True)), key=lambda p: p.get("order", 999))
    print(f"Building {len(projects)} published projects")

    write("index.html", build_home(site, projects))
    write("about/index.html", build_about(site))
    for i, p in enumerate(projects):
        nxt = projects[(i + 1) % len(projects)] if len(projects) > 1 else None
        write(f"work/{p['slug']}/index.html", build_project(site, p, nxt, pipelines))
    write("404.html", build_404(site))
    write("sitemap.xml", build_sitemap(site, projects))
    write("robots.txt", f"User-agent: *\nAllow: /\n\nSitemap: {site['url']}sitemap.xml\n")
    clean_stale_work_dirs({p["slug"] for p in projects})
    print("Done. Run `python3 tools/check.py` to validate links and list missing media.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
