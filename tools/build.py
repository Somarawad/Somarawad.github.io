def media_map(p: dict) -> dict:
    return {m["id"]: m for m in p.get("media", [])}


def hero_slot(p: dict):
    """The slot with id 'hero'; else the first slot, unless the project leads with a stats card."""
    mm = media_map(p)
    if "hero" in mm:
        return mm["hero"]
    if p.get("card_stats"):
        return None
    return (p.get("media") or [None])[0]


def stats_block(stats: list, cls: str = "") -> str:
    if not stats:
        return ""
    items = "".join(
        f'<div class="stat"><dt class="stat__label">{inline(s["label"])}</dt>'
        f'<dd class="stat__value">{esc(s["value"])}</dd></div>' for s in stats
    )
    return f'<dl class="stats {cls}">{items}</dl>'


def render_card(p: dict, root: str, idx: int) -> str:
    title = p.get("card_title") or p["title"]
    pal = p.get("palette")
    href = f"{root}work/{p['slug']}/"
    hero = hero_slot(p)
    badge = '<span class="badge badge--wip">Work in progress</span>' if p.get("wip") else ""
    if p.get("card_stats"):
        stat_src = next((s for s in p.get("sections", []) if s.get("type") == "stats"), None)
        visual = (f'<div class="card__stats" style="{palette_style(pal)}">'
                  f'{stats_block(stat_src["stats"] if stat_src else [], "stats--card")}</div>')
    else:
        visual = ""
        if hero and hero.get("type") == "video" and exists(hero.get("src", "")):
            poster = hero.get("poster", "")
            pa = f' poster="{root}{esc(poster)}"' if exists(poster) else ""
            visual = (f'<video class="card__video" muted loop playsinline preload="none"{pa} data-hover aria-hidden="true">'
                      f'<source src="{root}{esc(hero["src"])}" type="video/mp4"></video>')
        elif hero and hero.get("type") in ("video", "embed") and exists(hero.get("poster", "")):
            visual = img_tag(hero["poster"], "", root)
        elif hero and hero.get("type") == "image" and exists(hero.get("src", "")):
            visual = img_tag(hero["src"], "", root)
        elif hero and hero.get("type") == "compare" and exists(hero.get("after", "")):
            visual = img_tag(hero["after"], "", root)
        else:
            expected = (hero or {}).get("poster") or (hero or {}).get("src") or (hero or {}).get("after", "")
            visual = placeholder(p["title"], p.get("category", ""), expected, pal, "ph--card", alt="")
            visual = visual.replace('role="img" ', 'aria-hidden="true" ')
    meta = " · ".join(x for x in [p.get("category"), p.get("year")] if x)
    size = " card--feature" if p.get("featured") else ""
    return (
        f'<li class="card{size}" data-reveal>'
        f'<a class="card__link" href="{href}">'
        f'<div class="card__media">{visual}{badge}</div>'
        f'<div class="card__body">'
        f'<p class="card__meta">{esc(meta)}</p>'
        f'<h3 class="card__title">{esc(title)}</h3>'
        f'<p class="card__summary">{inline(p.get("summary", ""))}</p>'
        f'<span class="card__cta" aria-hidden="true">Case study <span class="arrow">→</span></span>'
        f"</div></a></li>"
    )


