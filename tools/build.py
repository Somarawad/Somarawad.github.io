def esc(s) -> str:
    return html.escape(str(s if s is not None else ""), quote=True)


def inline(text: str, root: str = "") -> str:
    """Escape text, then allow a tiny bit of markup:
    *emphasis*, **strong**, [label](url)."""
    s = esc(text)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\*(.+?)\*", r"<em>\1</em>", s)

    def link(m):
        label, url = m.group(1), m.group(2)
        ext = url.startswith(("http://", "https://", "mailto:"))
        href = url if ext else root + url
        rel = ' rel="noopener"' if ext and not url.startswith("mailto:") else ""
        return f'<a href="{href}"{rel}>{label}</a>'

    s = re.sub(r"\[(.+?)\]\((.+?)\)", link, s)
    return s


def plain(text: str) -> str:
    """Strip the inline markup for meta tags."""
    t = re.sub(r"\*\*?(.+?)\*\*?", r"\1", text or "")
    t = re.sub(r"\[(.+?)\]\((.+?)\)", r"\1", t)
    return t


def exists(rel: str) -> bool:
    return bool(rel) and (ROOT / rel).is_file()


def render(template: str, ctx: dict) -> str:
    def sub(m):
        key = m.group(1)
        if key not in ctx:
            raise KeyError(f"template variable '{key}' not provided")
        return str(ctx[key])

    return re.sub(r"\{\{\s*([a-zA-Z0-9_]+)\s*\}\}", sub, template)


def load_template(name: str) -> str:
    return (TEMPLATES / name).read_text(encoding="utf-8")


def write(rel: str, content: str) -> None:
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"  wrote {rel}")


def palette_style(pal) -> str:
    a, b = (pal or ["#161412", "#4a3a2a"])[:2]
    return f"--ph-a:{esc(a)};--ph-b:{esc(b)}"


