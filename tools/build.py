def render_section(sec: dict, p: dict, pipelines: dict, root: str) -> str:
    t = sec["type"]
    mm = media_map(p)
    pal = p.get("palette")
    title = p["title"]
    head = f'<h2 class="section__title">{inline(sec["heading"], root)}</h2>' if sec.get("heading") else ""
    intro = f'<p class="section__intro muted">{inline(sec["intro"], root)}</p>' if sec.get("intro") else ""
    body = ""
    cls = f"block block--{t}"
    if t == "text":
        paras = sec.get("body", [])
        if isinstance(paras, str):
            paras = [paras]
        body = "".join(f"<p>{inline(x, root)}</p>" for x in paras)
        body = f'<div class="prose">{body}</div>'
    elif t == "list":
        body = '<ul class="did">' + "".join(f"<li>{inline(x, root)}</li>" for x in sec.get("items", [])) + "</ul>"
    elif t == "steps":
        lis = "".join(
            f'<li class="step"><span class="step__num" aria-hidden="true">{i + 1:02d}</span>'
            f'<h3 class="step__title">{inline(it["title"], root)}</h3><p class="step__body">{inline(it.get("body", ""), root)}</p></li>'
            for i, it in enumerate(sec.get("items", []))
        )
        body = f'<ol class="steps" role="list">{lis}</ol>'
    elif t == "pipeline":
        body = render_pipeline(sec["pipeline"], pipelines)
    elif t == "compare":
        body = '<div class="stack">' + "".join(render_compare(mm[i], title, pal, root) for i in sec["media"]) + "</div>"
    elif t == "gallery":
        ids = sec["media"]
        n = len(ids)
        gcls = "gallery--1" if n == 1 else ("gallery--2" if n in (2, 4) else "gallery--3")
        body = f'<div class="gallery {gcls}">' + "".join(render_figure(mm[i], title, pal, root) for i in ids) + "</div>"
    elif t == "film":
        body = render_figure(mm[sec["media"]], title, pal, root, mode="controls", cls="media--film")
    elif t == "stats":
        shot = ""
        if sec.get("media"):
            shot = render_figure(mm[sec["media"]], title, pal, root, cls="media--shot")
        body = (f'<div class="statcard" style="{palette_style(pal)}">'
                f'{stats_block(sec.get("stats", []), "stats--big")}{shot}</div>')
    else:
        raise ValueError(f"{p['slug']}: unknown section type '{t}'")
    return f'<section class="{cls} wrap" data-reveal>{head}{intro}{body}</section>'


